using System.Text;
using helengine.baseplatform.Manifest;

namespace helengine.ps1.builder;

/// <summary>
/// Writes the generated scene catalog translation unit that the PS1 host turns into Core's
/// RuntimeSceneCatalog: one C array of scene id to cooked relative path pairs plus the startup id.
/// The files live beside generated Core and are linked separately from the unity source.
/// </summary>
public sealed class PlayStation1StartupManifestWriter {
    /// <summary>Resolves each manifest scene to its cooked scene artifact and writes the catalog sources.</summary>
    /// <param name="generatedCoreCppRootPath">Generated Core root receiving ps1_runtime_scene_catalog.hpp/.cpp.</param>
    /// <param name="manifest">Cooked build manifest.</param>
    /// <returns>Path of the written header.</returns>
    public string Write(string generatedCoreCppRootPath, PlatformBuildManifest manifest) {
        if (manifest == null) throw new ArgumentNullException(nameof(manifest));
        ValidateLoadingPolicy(manifest);
        PlatformBuildArtifact[] sceneArtifacts = manifest.CookedArtifacts
            .Where(artifact => string.Equals(artifact.ArtifactKind, "scene", StringComparison.OrdinalIgnoreCase))
            .ToArray();
        KeyValuePair<string, string>[] entries = manifest.Scenes.Select(scene => {
            PlatformBuildArtifact artifact = sceneArtifacts.FirstOrDefault(candidate => string.Equals(candidate.LogicalArtifactId, scene.SceneId, StringComparison.Ordinal));
            if (artifact == null) {
                string normalizedSourceIdentity = PlayStation1ContentStager.NormalizeRelativePath(scene.SourceIdentity);
                artifact = sceneArtifacts.FirstOrDefault(candidate => string.Equals(PlayStation1ContentStager.NormalizeRelativePath(candidate.RelativePath), normalizedSourceIdentity, StringComparison.Ordinal));
            }
            // Preserve legacy single-scene manifests without assigning one scene's payload to another scene.
            if (artifact == null && sceneArtifacts.Length == 1 && manifest.Scenes.Length == 1) artifact = sceneArtifacts[0];
            if (artifact == null) throw new InvalidOperationException($"PS1 startup scene '{scene.SceneId}' has no cooked scene artifact in the manifest.");
            return new KeyValuePair<string, string>(scene.SceneId, artifact.RelativePath);
        }).ToArray();
        return Write(generatedCoreCppRootPath, manifest.StartupSceneId, entries);
    }

    /// <summary>Rejects invalid budgets and loading scenes outside the packaged catalog before emitting native sources.</summary>
    /// <param name="manifest">Final cooked manifest containing operational scene identifiers.</param>
    static void ValidateLoadingPolicy(PlatformBuildManifest manifest) {
        if (!double.IsFinite(manifest.SceneLoadingBudgetMilliseconds) || manifest.SceneLoadingBudgetMilliseconds <= 0d) {
            throw new InvalidOperationException("PS1 scene loading requires a finite, positive millisecond budget.");
        }
        if (string.IsNullOrEmpty(manifest.LoadingScreenSceneId)) return;
        if (manifest.Scenes.Count(scene => string.Equals(scene.SceneId, manifest.LoadingScreenSceneId, StringComparison.Ordinal)) != 1) {
            throw new InvalidOperationException($"PS1 loading-screen scene '{manifest.LoadingScreenSceneId}' must identify exactly one packaged scene.");
        }
    }

    /// <summary>Writes the catalog sources for explicit scene id to cooked path pairs.</summary>
    /// <param name="generatedCoreCppRootPath">Generated Core root receiving the files.</param>
    /// <param name="startupSceneId">Scene the host loads at boot; must be one of the entries.</param>
    /// <param name="entries">Scene id to cooked relative path pairs.</param>
    /// <returns>Path of the written header.</returns>
    public string Write(string generatedCoreCppRootPath, string startupSceneId, IReadOnlyList<KeyValuePair<string, string>> entries) {
        if (string.IsNullOrWhiteSpace(generatedCoreCppRootPath)) throw new ArgumentException("Generated Core root is required.", nameof(generatedCoreCppRootPath));
        if (string.IsNullOrWhiteSpace(startupSceneId)) throw new ArgumentException("Startup scene id is required.", nameof(startupSceneId));
        if (entries == null || entries.Count == 0) throw new InvalidOperationException("PS1 startup catalog requires at least one scene.");
        if (!entries.Any(entry => string.Equals(entry.Key, startupSceneId, StringComparison.Ordinal))) {
            throw new InvalidOperationException($"PS1 startup scene '{startupSceneId}' is missing from the catalog.");
        }

        string root = Path.GetFullPath(generatedCoreCppRootPath);
        Directory.CreateDirectory(root);
        StringBuilder header = new();
        header.AppendLine("// Generated by helengine.ps1.builder; do not edit.");
        header.AppendLine("#pragma once");
        header.AppendLine("#include <cstddef>");
        header.AppendLine("struct HEPs1RuntimeSceneCatalogEntry { const char* SceneId; const char* CookedRelativePath; };");
        header.AppendLine("extern \"C\" const char* he_ps1_runtime_startup_scene_id();");
        header.AppendLine("extern \"C\" const HEPs1RuntimeSceneCatalogEntry* he_ps1_runtime_scene_catalog_entries(std::size_t* count);");
        string headerPath = Path.Combine(root, "ps1_runtime_scene_catalog.hpp");
        File.WriteAllText(headerPath, header.ToString(), new UTF8Encoding(false));

        HashSet<string> ids = new(StringComparer.Ordinal);
        StringBuilder source = new();
        source.AppendLine("// Generated by helengine.ps1.builder; do not edit.");
        source.AppendLine("#include \"ps1_runtime_scene_catalog.hpp\"");
        source.AppendLine("namespace {");
        source.AppendLine("const HEPs1RuntimeSceneCatalogEntry kEntries[] = {");
        foreach (KeyValuePair<string, string> entry in entries) {
            if (string.IsNullOrWhiteSpace(entry.Key) || string.IsNullOrWhiteSpace(entry.Value)) throw new InvalidOperationException("PS1 startup catalog contains an incomplete entry.");
            if (!ids.Add(entry.Key)) throw new InvalidOperationException($"PS1 startup catalog contains duplicate scene id '{entry.Key}'.");
            source.Append("{\"").Append(Escape(entry.Key)).Append("\", \"").Append(Escape(PlayStation1ContentStager.NormalizeRelativePath(entry.Value))).AppendLine("\"},");
        }
        source.AppendLine("};");
        source.Append("const char kStartupSceneId[] = \"").Append(Escape(startupSceneId)).AppendLine("\";");
        source.AppendLine("}");
        source.AppendLine("extern \"C\" const char* he_ps1_runtime_startup_scene_id() { return kStartupSceneId; }");
        source.AppendLine("extern \"C\" const HEPs1RuntimeSceneCatalogEntry* he_ps1_runtime_scene_catalog_entries(std::size_t* count) { if (count != nullptr) *count = sizeof(kEntries) / sizeof(kEntries[0]); return kEntries; }");
        File.WriteAllText(Path.Combine(root, "ps1_runtime_scene_catalog.cpp"), source.ToString(), new UTF8Encoding(false));
        return headerPath;
    }

    /// <summary>Escapes a value for use inside a C string literal.</summary>
    static string Escape(string value) => value
        .Replace("\\", "\\\\", StringComparison.Ordinal)
        .Replace("\"", "\\\"", StringComparison.Ordinal)
        .Replace("\r", "\\r", StringComparison.Ordinal)
        .Replace("\n", "\\n", StringComparison.Ordinal);
}
