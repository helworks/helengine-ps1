bool Ps1NumericPolicySelfTest::Matches(std::uint16_t expected, std::uint16_t observed, unsigned tolerance) {
    const bool expectedNaN = (expected & 0x7c00u) == 0x7c00u && (expected & 0x03ffu) != 0;
    const bool observedNaN = (observed & 0x7c00u) == 0x7c00u && (observed & 0x03ffu) != 0;
    if (expectedNaN) return observedNaN;
    if (observedNaN) return false;
    const unsigned difference = expected > observed ? expected - observed : observed - expected;
    return difference <= tolerance;
}

